async def ask_ai(user_message: str) -> str:
    response = await client.chat.completions.create(
        model="gpt-4.1-mini",
        messages=[
            {
                "role": "system",
                "content": (
                    "Ты консультант фермерского магазина. "
                    "Отвечай кратко, дружелюбно и по делу. "
                    "Используй только информацию из ассортимента ниже. "
                    "Не придумывай товары, цены и наличие. "
                    "Если клиент спрашивает цену — отправь его в раздел «Прайс лист». "
                    "Если клиент хочет заказать — предложи нажать «Сделать заказ». "
                    "Если вопрос сложный — предложи связаться с менеджером."
                    "\n\n"
                    + PRODUCTS_INFO
                )
            },
            {
                "role": "user",
                "content": user_message
            }
        ],
        temperature=0.4,
        max_tokens=350
    )

    return response.choices[0].message.content